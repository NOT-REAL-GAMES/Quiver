#define PATH_CAP 4096
#define TOKEN_CAP 4096

typedef struct { char *text; int line; } token_t;
typedef struct { token_t *items; size_t count, capacity; } tokens_t;
static const char *source_name;
static void error_at(int line, const char *message) { fprintf(stderr, "%s:%d: %s\n", source_name ? source_name : "quiverscript", line, message); }
static int path_join(char *dst, const char *a, const char *b) {
    int n=snprintf(dst, PATH_CAP, "%s/%s", a, b); return n>=0 && n<PATH_CAP;
}
static int absolute_path(char *dst, const char *path) {
#ifdef _WIN32
    return _fullpath(dst, path, PATH_CAP) != NULL;
#else
    if (path[0]=='/') {int n=snprintf(dst,PATH_CAP,"%s",path);return n>=0 && n<PATH_CAP;}
    char cwd[PATH_CAP];return getcwd(cwd,sizeof(cwd)) && path_join(dst,cwd,path);
#endif
}
static int make_dir(const char *path) {
    if (!MKDIR(path) || errno==EEXIST) return 1;
    fprintf(stderr, "Cannot create %s: %s\n", path, strerror(errno)); return 0;
}
static char *read_file(const char *path) {
    FILE *f=fopen(path,"rb"); long n; char *s;
    if (!f) { fprintf(stderr,"Cannot read %s: %s\n",path,strerror(errno)); return NULL; }
    if (fseek(f,0,SEEK_END) || (n=ftell(f))<0 || n>16*1024*1024 || fseek(f,0,SEEK_SET)) { fclose(f); return NULL; }
    s=malloc((size_t)n+1); if (!s) { fclose(f); return NULL; }
    if (fread(s,1,(size_t)n,f)!=(size_t)n) { free(s); fclose(f); return NULL; }
    s[n]=0; fclose(f); return s;
}
static int copy_file(const char *src,const char *dst) {
    FILE *in=fopen(src,"rb"), *out=NULL; char buf[16384]; size_t n; int ok=1;
    if (!in || !(out=fopen(dst,"wb"))) { fprintf(stderr,"Cannot copy %s to %s: %s\n",src,dst,strerror(errno)); if(in)fclose(in); return 0; }
    while ((n=fread(buf,1,sizeof(buf),in))) if (fwrite(buf,1,n,out)!=n) {ok=0;break;}
    if (ferror(in)) ok=0;
    if (fclose(out)) ok=0;
    fclose(in); if (!ok) fprintf(stderr,"Failed copying %s\n",src); return ok;
}
static int add_token(tokens_t *t,const char *start,size_t len,int line) {
    if(len>=TOKEN_CAP) {error_at(line,"token too long");return 0;}
    if(t->count==t->capacity) {size_t c=t->capacity?t->capacity*2:128; token_t *p=realloc(t->items,c*sizeof(*p)); if(!p)return 0;t->items=p;t->capacity=c;}
    char *s=malloc(len+1);if(!s)return 0;memcpy(s,start,len);s[len]=0;t->items[t->count++]=(token_t){s,line};return 1;
}
static void free_tokens(tokens_t *t) {for(size_t i=0;i<t->count;i++)free(t->items[i].text);free(t->items);}
static int tokenize(const char *p,tokens_t *t) {
    int line=1;
    while(*p) {
        if(isspace((unsigned char)*p)) {if(*p=='\n')line++;p++;continue;}
        if(p[0]=='/'&&p[1]=='/') {while(*p&&*p!='\n')p++;continue;}
        if(p[0]=='/'&&p[1]=='*') {int start=line;p+=2;while(*p&&!(p[0]=='*'&&p[1]=='/')) {if(*p=='\n')line++;p++;}if(!*p){error_at(start,"unterminated comment");return 0;}p+=2;continue;}
        const char *start=p;int at=line;
        if(isalpha((unsigned char)*p)||*p=='_') {while(isalnum((unsigned char)*p)||*p=='_')p++;}
        else if(isdigit((unsigned char)*p)||(*p=='.'&&isdigit((unsigned char)p[1]))) {
            char *end; (void)strtod(p,&end); if(end==p){error_at(at,"invalid number");return 0;}p=end;
        } else if(*p=='"'||*p=='\'') {
            char quote=*p++;while(*p&&*p!=quote) {if(*p=='\n'){error_at(at,"newline in literal");return 0;}if(*p=='\\'&&p[1])p++;p++;}
            if(!*p){error_at(at,"unterminated literal");return 0;}p++;
        } else if(strchr("{}()[];,.+-*/%=!<>|&",*p)) {
            p++;if((*p=='='&&strchr("+-*/%=!<>",p[-1]))||(*p==p[-1]&&strchr("&|+-",*p)))p++;
        } else {error_at(at,"invalid character");return 0;}
        if(!add_token(t,start,(size_t)(p-start),at))return 0;
    }
    return 1;
}
static int is_type(const char *s) {return !strcmp(s,"void")||!strcmp(s,"float")||!strcmp(s,"bool")||!strcmp(s,"vector")||!strcmp(s,"string")||!strcmp(s,"entity");}
static const char *mapped(const char *s) {if(!strcmp(s,"bool"))return "float";if(!strcmp(s,"true"))return "1";if(!strcmp(s,"false"))return "0";return s;}
static int is_ident(const char *s) {if(!isalpha((unsigned char)*s)&&*s!='_')return 0;for(s++;*s;s++)if(!isalnum((unsigned char)*s)&&*s!='_')return 0;return 1;}
static int emit(tokens_t *t,FILE *out) {
    size_t i=0;int depth=0, output_line=1;
    fprintf(out,"/* Generated by QuiverScript; semantic checks are performed by FTEQCC. */\nfloat(float x) sin = #60;\nfloat(float x) sqrt = #62;\n");
    if (!source_name || strpbrk(source_name, "()\r\n")) { error_at(1,"source filename contains unsupported characters"); return 0; }
    fprintf(out,"#pragma file(%s)\n#pragma line(1)\n",source_name);
    while(i<t->count) {
        const char *s=t->items[i].text;int line=t->items[i].line;
        while(output_line<line) {fputc('\n',out);output_line++;}
        if (!strcmp(s,"struct") || !strcmp(s,"class") || !strcmp(s,"switch") ||
            !strcmp(s,"case") || !strcmp(s,"[") || !strcmp(s,"]")) {
            error_at(line,"unsupported QuiverScript construct"); return 0;
        }
        if(depth==0 && is_type(s) && i+2<t->count && is_ident(t->items[i+1].text) && !strcmp(t->items[i+2].text,"(")) {
            const char *type=mapped(s),*name=t->items[i+1].text;size_t j=i+3;int paren=1;
            while(j<t->count&&paren) {if(!strcmp(t->items[j].text,"("))paren++;else if(!strcmp(t->items[j].text,")"))paren--;j++;}
            if(paren||j>=t->count||strcmp(t->items[j].text,"{")) {error_at(line,"expected a function body after parameter list");return 0;}
            fprintf(out,"%s ( ",type);
            for(size_t k=i+3;k+1<j;k++)fprintf(out,"%s ",mapped(t->items[k].text));
            fprintf(out,") %s = { ",name);
            while(output_line<t->items[j].line) {fputc('\n',out);output_line++;}
            depth=1;i=j+1;continue;
        }
        if(!strcmp(s,"{"))depth++;
        if(!strcmp(s,"}")) {if(!depth){error_at(line,"unexpected '}'");return 0;}depth--;fprintf(out,depth?"} ":"}; ");i++;continue;}
        if(depth==0 && !is_type(s)) {error_at(line,"expected a typed function or global declaration");return 0;}
        if(depth==0) {
            /* Emit module-level declaration through its terminating semicolon. */
            while(i<t->count&&strcmp(t->items[i].text,";")) {if(!strcmp(t->items[i].text,"{")){error_at(line,"invalid global declaration");return 0;}fprintf(out,"%s ",mapped(t->items[i++].text));}
            if(i==t->count){error_at(line,"expected ';'");return 0;}fputs("; ",out);i++;continue;
        }
        fprintf(out,"%s ",mapped(s));i++;
    }
    if(depth){error_at(t->count?t->items[t->count-1].line:1,"unterminated function body");return 0;}
    return !ferror(out);
}
static int transpile(const char *input,const char *output) {
    source_name=input;char *src=read_file(input);tokens_t tokens={0};FILE *out=NULL;int ok=0;
    if(!src)return 0;
    if(!tokenize(src,&tokens))goto done;
    out=fopen(output,"wb");if(!out){fprintf(stderr,"Cannot write %s: %s\n",output,strerror(errno));goto done;}
    ok=emit(&tokens,out);if(fclose(out))ok=0;out=NULL;
    if(!ok)remove(output);
 done:if(out)fclose(out);free(src);free_tokens(&tokens);return ok;
}
static int run_qcc(const char *qcc,const char *src) {
#ifdef _WIN32
    char cwd[PATH_CAP]; if (!_getcwd(cwd,sizeof(cwd)) || _chdir(src)) return 0;
    const char *args[]={qcc,"-O0",NULL}; intptr_t status=_spawnv(_P_WAIT,qcc,args); _chdir(cwd); return status==0;
#else
    pid_t child=fork();if(child<0){perror("fork");return 0;}if(!child){if(chdir(src)){perror(src);_exit(127);}execl(qcc,qcc,"-O0",(char*)NULL);perror(qcc);_exit(127);}
    int status;while(waitpid(child,&status,0)<0)if(errno!=EINTR){perror("waitpid");return 0;}return WIFEXITED(status)&&WEXITSTATUS(status)==0;
#endif
}
static int build(const char *script,const char *game,const char *qcc,const char *source) {
    char work[PATH_CAP],qc[PATH_CAP],path[PATH_CAP],dest[PATH_CAP],generated[PATH_CAP],built[PATH_CAP],final[PATH_CAP],qcc_path[PATH_CAP];
    if (!absolute_path(qcc_path,qcc)) {fprintf(stderr,"Invalid compiler path: %s\n",qcc);return 0;}
    if(!path_join(work,game,"quiverscript")||!path_join(qc,work,"qc")||!make_dir(game)||!make_dir(work)||!make_dir(qc))return 0;
    if(!path_join(path,source,"progs.src"))return 0;
    char *manifest=read_file(path);if(!manifest)return 0;
    if(!path_join(dest,qc,"progs.src")){free(manifest);return 0;}
    FILE *out=fopen(dest,"wb");if(!out){free(manifest);return 0;}fprintf(out,"../progs.dat\n");
    char *line=strtok(manifest,"\n\r"); /* skip original output path */
    while((line=strtok(NULL,"\n\r"))) {
        while(isspace((unsigned char)*line))line++;
        if(!*line || (*line=='/'&&line[1]=='/'))continue;
        char name[256];size_t n=0;while(line[n]&&!isspace((unsigned char)line[n])&&n<sizeof(name)-1){name[n]=line[n];n++;}name[n]=0;
        if(!n||strstr(name,"..")||strchr(name,'/')||strchr(name,'\\')||!path_join(path,source,name)||!path_join(dest,qc,name)||!copy_file(path,dest)){fclose(out);free(manifest);return 0;}
        fprintf(out,"%s\n",name);
    }
    free(manifest);fprintf(out,"quiverscript_generated.qc\n");if(fclose(out))return 0;
    if(!path_join(generated,qc,"quiverscript_generated.qc")||!transpile(script,generated))return 0;
    if(!path_join(dest,work,"generated.qc")||!copy_file(generated,dest))return 0;
    if(!run_qcc(qcc_path,qc)){fprintf(stderr,"QuakeC compilation failed; package was not updated\n");return 0;}
    if(!path_join(built,work,"progs.dat")||!path_join(final,game,"progs.dat.tmp")||!copy_file(built,final))return 0;
    if(!path_join(dest,game,"progs.dat"))return 0;
#ifdef _WIN32
    if(!MoveFileExA(final,dest,MOVEFILE_REPLACE_EXISTING|MOVEFILE_WRITE_THROUGH)) {
        fprintf(stderr,"Cannot install %s: Windows error %lu\n",dest,(unsigned long)GetLastError());return 0;
    }
#else
    if(rename(final,dest)){fprintf(stderr,"Cannot install %s: %s\n",dest,strerror(errno));return 0;}
#endif
    printf("QuiverScript package built: %s\n",dest);return 1;
}
int main(int argc,char **argv) {
    if(argc==4&&!strcmp(argv[1],"transpile"))return transpile(argv[2],argv[3])?0:1;
    if(argc==10&&!strcmp(argv[1],"build")) {
        const char *script=NULL,*game=NULL,*qcc=NULL,*source=NULL;
        for(int i=2;i+1<argc;i+=2) {
            if(!strcmp(argv[i],"--script"))script=argv[i+1];else if(!strcmp(argv[i],"--game-dir"))game=argv[i+1];
            else if(!strcmp(argv[i],"--qcc"))qcc=argv[i+1];else if(!strcmp(argv[i],"--qc-source"))source=argv[i+1];else break;
        }
        if(script&&game&&qcc&&source)return build(script,game,qcc,source)?0:1;
    }
    fprintf(stderr,"Usage: quiverscript transpile INPUT.qs OUTPUT.qc\n       quiverscript build --script INPUT.qs --game-dir DIR --qcc FTEQCC --qc-source ID1_SOURCES\n");return 2;
}
