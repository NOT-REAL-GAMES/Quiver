#!/usr/bin/env python3
"""Isolated graphical planet generation/construction/wrapping smoke.

Only pak assets are linked. Configurations, worlds, imported OBJ fixtures,
shader validation logs, screenshots and measurements remain in /tmp. Host
frame times include scheduling and presentation and are not GPU pass timings.
Captures require visual review; success means commands, bounded queues,
canonical coordinates, persistence and renderer lifecycle checks passed.
"""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import time

from run_terrain_lod_smoke import Run, WRAPPER
from run_terrain_lighting_smoke import photograph
from run_terrain_smoothing_smoke import world_status


def cube_obj():
    vertices = [tuple(64 if i & (1 << axis) else -64 for axis in range(3)) for i in range(8)]
    lines = ["v " + " ".join(map(str, v)) for v in vertices] + ["usemtl stone"]
    for axis in range(3):
        for side in range(2):
            base, u, v = side << axis, 1 << ((axis + 1) % 3), 1 << ((axis + 2) % 3)
            for face in ([base, base | u, base | u | v], [base, base | u | v, base | v]):
                if not side:
                    face.reverse()
                lines.append("f " + " ".join(str(i + 1) for i in face))
    return "\n".join(lines) + "\n"


def teleport(run, chunks, local=(128, 128, 512), angles=(10, 45, 0)):
    output = run.command("world_teleport " + " ".join(map(str, (*chunks, *local))))
    expected = [chunks[0] % 1250048, chunks[1] % 1250048, chunks[2]]
    match = re.search(r"Teleported to chunk (-?\d+) (-?\d+) (-?\d+)", output)
    if not match or list(map(int, match.groups())) != expected:
        raise RuntimeError("teleport did not canonicalize: " + output)
    run.command("setpos " + " ".join(map(str, (*local, *angles))))
    run.delay(.3)
    return expected


def settle(run):
    start = time.monotonic()
    status = None
    while time.monotonic() - start < run.args.stage_timeout:
        status = world_status(run)
        if not status["pending_chunks"] and not status["mesh_jobs"]:
            return run.settle(True, idle_uploads=True)
        run.delay(.2)
    raise RuntimeError(f"planet worker queue did not drain within {run.args.stage_timeout:g} seconds: {status}")


def committed(run, command, expected):
    output = run.command(command)
    if expected not in output:
        raise RuntimeError("command was not committed: " + output)
    return output.strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--basedir", type=Path, required=True)
    parser.add_argument("--timeout", type=float, default=600)
    parser.add_argument("--stage-timeout", type=float, default=60)
    parser.add_argument("--sample-seconds", type=float, default=2)
    parser.add_argument("--width", type=int, default=1280)
    parser.add_argument("--height", type=int, default=720)
    parser.add_argument("--validation", action="store_true")
    parser.add_argument("--capture-only", action="store_true", help="skip host timings while other work runs")
    parser.add_argument("--render-focus", action="store_true", help="construction and mountains only, followed by MSAA/cloud redraws; skip persistence, wrap and cliff/coast tour")
    parser.add_argument("--global-cache", type=Path, help="reuse a cache generated by this exact candidate (useful for debug validation)")
    args = parser.parse_args()
    if not 0 < args.timeout <= 1200 or not 0 < args.stage_timeout <= 180 or not .25 <= args.sample_seconds <= 15:
        parser.error("timeout/stage/sample bounds are 1200/180/15 seconds")
    source = args.basedir.resolve()
    if (source / "id1").is_dir():
        source /= "id1"
    assets = sorted(source.glob("pak*.pak"))
    if not assets:
        parser.error("no pak*.pak assets found")
    work = Path(tempfile.mkdtemp(prefix="quiver-planet-smoke-"))
    (work / "id1").mkdir()
    (work / "user").mkdir()
    if args.global_cache:
        (work / "id1/worlds").mkdir()
        shutil.copy2(args.global_cache, work / "id1/worlds/planet_smoke.sqlite3.planetcache")
    for asset in assets:
        (work / "id1" / asset.name).symlink_to(asset.resolve())
    shutil.copy2(args.binary.resolve(), work / "vkquake")
    (work / "cube.obj").write_text(cube_obj())
    (work / "autokey.c").write_text(WRAPPER)
    subprocess.run(["cc", "-shared", "-fPIC", "-O2", str(work / "autokey.c"), "-o", str(work / "autokey.so"), "-ldl"], check=True, timeout=30)
    (work / "id1/startup.cfg").write_text('''vid_fullscreen 0
vid_vsync 0
vid_fsaa 0
host_maxfps 0
r_tasks 1
r_parallelmark 1
r_indirect 1
r_gpulightmapupdate 1
r_scale 1
r_fastsky 1
r_clouds 0
r_drawviewmodel 0
viewsize 130
cl_nocsqc 1
developer 1
scr_conspeed 100000
con_notifytime -1
world_view_chunks 1
r_octree_distance 4096
r_octree_mesh_mb 128
r_octree_upload_mb 8
gl_farclip 524288
r_octree_lod 1
r_octree_lod_distance 262144
r_octree_smooth 1
r_sun_angle 35
bind F12 "exec smoke_command.cfg"
world_create planet_smoke planet 1
''')
    (work / "id1/vkQuake.cfg").write_text(f"vid_fullscreen 0\nvid_width {args.width}\nvid_height {args.height}\nvid_vsync 0\nvid_fsaa 0\n")
    summary = {"success": False, "work": str(work), "binary": str(args.binary.resolve()), "checks": {},
               "scope": "construction/mountain renderer regression" if args.render_focus else "complete planet smoke",
               "validation_requested": args.validation,
               "visual_review_required": True, "reused_global_cache": bool(args.global_cache), "timing_method": "uncapped host input-batch frame intervals, clouds off"}
    run = None
    print(str(work), flush=True)
    try:
        started = time.monotonic()
        run = Run(args, work)
        run.wait(lambda text: "CL_SignonReply: 4" in text, "planet signon")
        summary["startup_seconds"] = time.monotonic() - started
        run.command("noclip")
        for curved in (() if args.render_focus else (0, 1)):
            run.command(f"r_planet_curvature {curved}")
            teleport(run, (0, 0, 2), angles=(5, 45, 0))
            label = f"horizon_curvature{curved}"
            summary["checks"][label] = {"stats": settle(run), "screenshot": photograph(run, label), "host_frames": None if args.capture_only or args.validation else run.measure(label)}
        if args.render_focus:
            run.command("r_planet_curvature 1")
        teleport(run, (0, 0, 0), local=(128,128,256), angles=(15,45,0))
        summary["checks"]["spawn"] = {"stats": settle(run), "screenshot": photograph(run, "spawn")}
        summary["checks"]["box"] = committed(run, "world_brush add box 192 160 192 0 25 0", "Solid edit committed.")
        summary["checks"]["cut"] = committed(run, "world_brush subtract box 64 256 96 0 25 0", "Solid edit committed.")
        teleport(run, (0,0,0), local=(512,128,256))
        summary["checks"]["wedge"] = committed(run, "world_brush add wedge 192 160 128 0 -20 0", "Solid edit committed.")
        teleport(run, (0,0,0), local=(128,512,256))
        summary["checks"]["obj"] = committed(run, "world_import cube.obj", "Imported editable solid.")
        teleport(run, (0,0,0), local=(768,768,600), angles=(30,225,0))
        summary["checks"]["construction"] = {"stats": settle(run), "screenshot": photograph(run, "construction")}
        run.command("r_octree_lod 0")
        summary["checks"]["construction_near_only"] = {"stats": run.settle(False, idle_uploads=True), "screenshot": photograph(run, "construction_near_only")}
        run.command("r_octree_lod 1")
        if not args.render_focus:
            summary["checks"]["save"] = committed(run, "world_save", "World saved")
            run.map_command("world_load planet_smoke")
            run.command("noclip")
            teleport(run, (0,0,0), local=(768,768,600), angles=(30,225,0))
            summary["checks"]["reload"] = {"stats": settle(run), "screenshot": photograph(run, "reload")}
            summary["checks"]["wrap"] = {"canonical_chunk": teleport(run, (-1,1250048,2)), "stats": settle(run), "screenshot": photograph(run,"wrapped")}
            teleport(run, (5000,6000,40), angles=(35,45,0))
            summary["checks"]["continent"] = {"stats": settle(run), "screenshot": photograph(run, "continent")}
        destinations = (
            ("mountains", (908238, 322278, 130), (512,512,512), (20,225,0)),
            ("cliff", (927770, 283214, 118), (512,512,600), (10,0,0)),
            ("coast", (673854,1103558,0), (512,512,768), (15,90,0)),
        )
        for label, chunks, local, angles in (destinations[:1] if args.render_focus else destinations):
            teleport(run, chunks, local, angles)
            summary["checks"][label] = {"stats": settle(run), "screenshot": photograph(run, label)}
        run.command("vid_fsaa 4\nvid_restart")
        summary["checks"]["msaa4"] = {"stats": settle(run), "screenshot": photograph(run, "msaa4")}
        run.command("r_fastsky 0\nr_atmosphere 1\nr_clouds 1\nr_clouds_speed 0")
        run.delay(2)
        summary["checks"]["clouds_msaa4"] = {"stats": settle(run), "screenshot": photograph(run, "clouds_msaa4")}
        summary["world_stats"] = run.command("world_stats")
        run.command("echo PLANET_SMOKE_COMPLETE\nbind F12 quit")
        os.write(run.write_fd, b"k")
        run.process.wait(timeout=10)
        if run.process.returncode:
            raise RuntimeError(f"engine exit {run.process.returncode}")
        summary["success"] = True
    except Exception as error:
        summary["error"] = str(error)
    finally:
        if run is not None:
            run.close()
        if args.validation:
            process_log = work / "process.log"
            output = process_log.read_text(errors="replace") if process_log.exists() else ""
            failures = re.findall(r"[^\n]*(?:VUID-|Validation Error)[^\n]*", output)
            summary["validation_layer_enabled"] = "Using VK_LAYER_KHRONOS_validation" in output
            summary["validation_error_lines"] = failures[:16]
            summary["validation_error_count"] = len(failures)
            if failures or not summary["validation_layer_enabled"]:
                summary["success"] = False
                summary.setdefault("error", "Vulkan validation errors or validation layer was not enabled; inspect process.log")
        (work / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
        print(json.dumps({key: summary[key] for key in ("success", "work", "error") if key in summary}), flush=True)
    if not summary["success"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
